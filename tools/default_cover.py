#!/usr/bin/env python3
"""Generates the default game cover (data/default_game_cover.svg).

Retro synthwave: striped sun, mountains, perspective grid, CRT scanlines and a
5x7 pixel font drawn as rectangles (no font dependency, fully reproducible).
Render (librsvg + ImageMagick 7):
rsvg-convert -w 600 -h 900 data/default_game_cover.svg | magick - -strip -quality 90 -sampling-factor 4:4:4 data/default_game_cover.jpg
"""
import random
from pathlib import Path

W, H = 600, 900
HORIZON = 600
VP_X = W / 2

# 5x7 pixel glyphs, rows top to bottom.
FONT = {
    "K": ["10001", "10010", "10100", "11000", "10100", "10010", "10001"],
    "A": ["01110", "10001", "10001", "11111", "10001", "10001", "10001"],
    "P": ["11110", "10001", "10001", "11110", "10000", "10000", "10000"],
    "R": ["11110", "10001", "10001", "11110", "10100", "10010", "10001"],
    "E": ["11111", "10000", "10000", "11110", "10000", "10000", "11111"],
    "S": ["01111", "10000", "10000", "01110", "00001", "00001", "11110"],
    "T": ["11111", "00100", "00100", "00100", "00100", "00100", "00100"],
    " ": ["00000"] * 7,
}


def pixel_text(text: str, cx: float, top: float, px: float, gap: float) -> str:
    """Rectangles for `text` centred on cx; one path per glyph pixel row run."""
    width = len(text) * 5 * px + (len(text) - 1) * gap
    x0 = cx - width / 2
    rects = []
    for i, ch in enumerate(text):
        gx = x0 + i * (5 * px + gap)
        for r, row in enumerate(FONT[ch]):
            c = 0
            while c < 5:
                if row[c] == "1":
                    run = 1
                    while c + run < 5 and row[c + run] == "1":
                        run += 1
                    rects.append(f'<rect x="{gx + c * px:.1f}" y="{top + r * px:.1f}" width="{run * px:.1f}" height="{px:.1f}"/>')
                    c += run
                else:
                    c += 1
    return "".join(rects)


def stars() -> str:
    rnd = random.Random(7)
    out = []
    for _ in range(90):
        x, y = rnd.uniform(0, W), rnd.uniform(0, HORIZON - 120)
        r = rnd.choice([0.8, 0.8, 1.0, 1.4, 2.0])
        o = rnd.uniform(0.35, 0.95)
        out.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}" fill="#fff" opacity="{o:.2f}"/>')
    return "".join(out)


def grid() -> str:
    lines = []
    # Horizontal lines: spacing grows towards the viewer.
    y, step = HORIZON + 4, 6.0
    while y < H:
        lines.append(f'<line x1="0" y1="{y:.1f}" x2="{W}" y2="{y:.1f}"/>')
        y += step
        step *= 1.32
    # Vertical lines converge in the vanishing point.
    for i in range(-14, 15):
        x_bottom = VP_X + i * 70
        lines.append(f'<line x1="{VP_X + i * 6:.1f}" y1="{HORIZON}" x2="{x_bottom:.1f}" y2="{H}"/>')
    return "".join(lines)


def sun_mask() -> str:
    # Gaps widen towards the horizon, like the classic sunset.
    bars, y, h = [], 520.0, 3.0
    while y < HORIZON:
        bars.append(f'<rect x="0" y="{y:.1f}" width="{W}" height="{h:.1f}" fill="#000"/>')
        y += h + 9
        h += 2.5
    return f'<mask id="sunCut"><rect width="{W}" height="{H}" fill="#fff"/>{"".join(bars)}</mask>'


MOUNTAINS = (
    f"M0,{HORIZON} L0,540 L60,505 L110,530 L170,470 L230,520 L270,500 L300,515 "
    f"L340,480 L390,525 L450,460 L520,515 L560,495 L600,520 L600,{HORIZON} Z"
)

svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
<!-- KaKa default game cover. Generated by tools/default_cover.py; edit the script, not this file. -->
<defs>
  <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#07021a"/><stop offset="0.45" stop-color="#1d0742"/>
    <stop offset="0.8" stop-color="#5a0f6e"/><stop offset="1" stop-color="#ff2e88"/>
  </linearGradient>
  <linearGradient id="sun" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#fff36b"/><stop offset="0.45" stop-color="#ff9a2e"/><stop offset="1" stop-color="#ff2e88"/>
  </linearGradient>
  <linearGradient id="floor" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#2a0640"/><stop offset="1" stop-color="#05010f"/>
  </linearGradient>
  <linearGradient id="chrome" gradientUnits="userSpaceOnUse" x1="0" y1="120" x2="0" y2="232">
    <stop offset="0" stop-color="#e6fbff"/><stop offset="0.48" stop-color="#3de8ff"/>
    <stop offset="0.52" stop-color="#1b4bff"/><stop offset="1" stop-color="#ff4fd8"/>
  </linearGradient>
  <radialGradient id="glow" cx="0.5" cy="0.5" r="0.5">
    <stop offset="0" stop-color="#ff7ad9" stop-opacity="0.55"/><stop offset="1" stop-color="#ff7ad9" stop-opacity="0"/>
  </radialGradient>
  <radialGradient id="vignette" cx="0.5" cy="0.5" r="0.75">
    <stop offset="0.6" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity="0.55"/>
  </radialGradient>
  <filter id="blur" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="5"/></filter>
  <pattern id="scan" width="4" height="4" patternUnits="userSpaceOnUse"><rect width="4" height="1.4" fill="#000" opacity="0.22"/></pattern>
  {sun_mask()}
  <clipPath id="aboveHorizon"><rect width="{W}" height="{HORIZON}"/></clipPath>
</defs>

<rect width="{W}" height="{H}" fill="url(#sky)"/>
{stars()}
<ellipse cx="{VP_X}" cy="470" rx="290" ry="230" fill="url(#glow)"/>
<g clip-path="url(#aboveHorizon)">
  <circle cx="{VP_X}" cy="470" r="175" fill="url(#sun)" mask="url(#sunCut)"/>
</g>
<path d="{MOUNTAINS}" fill="#12052b"/>
<path d="{MOUNTAINS}" fill="none" stroke="#3de8ff" stroke-width="2" opacity="0.8"/>

<rect y="{HORIZON}" width="{W}" height="{H - HORIZON}" fill="url(#floor)"/>
<g stroke="#ff2bd6" stroke-width="5" opacity="0.45" filter="url(#blur)">{grid()}</g>
<g stroke="#ff6be6" stroke-width="2">{grid()}</g>
<line x1="0" y1="{HORIZON}" x2="{W}" y2="{HORIZON}" stroke="#ffd2f5" stroke-width="3"/>

<g fill="#ff2bd6" opacity="0.7" filter="url(#blur)">{pixel_text("KAKA", VP_X, 120, 16, 18)}</g>
<g fill="#130433" transform="translate(6,6)">{pixel_text("KAKA", VP_X, 120, 16, 18)}</g>
<g fill="url(#chrome)">{pixel_text("KAKA", VP_X, 120, 16, 18)}</g>

<rect x="140" y="772" width="320" height="56" rx="6" fill="#05010f" opacity="0.75"/>
<g fill="#3de8ff" opacity="0.8" filter="url(#blur)">{pixel_text("PRESS START", VP_X, 788, 4, 4)}</g>
<g fill="#e6fbff">{pixel_text("PRESS START", VP_X, 788, 4, 4)}</g>

<rect width="{W}" height="{H}" fill="url(#scan)"/>
<rect width="{W}" height="{H}" fill="url(#vignette)"/>
</svg>
"""

out = Path(__file__).resolve().parent.parent / "data" / "default_game_cover.svg"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(svg, encoding="utf-8")
print(out)
